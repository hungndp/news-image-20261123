export const FONT_W = 5;
export const FONT_H = 7;

// Width in pixels of `text` rendered at the given scale (1px tracking).
export function textWidth(text: string, scale: number): number {
  return text.length * (FONT_W + 1) * scale - scale;
}

// Wrap `text` into lines of at most `maxWidth` pixels at `scale`.
// Long words are split rather than dropped; never returns an empty list.
export function wrapText(text: string, scale: number, maxWidth: number): string[] {
  const words = text.toUpperCase().split(' ');
  const lines: string[] = [];
  let cur = '';
  const charW = (FONT_W + 1) * scale;
  for (const word of words) {
    let w = word;
    while (textWidth(w, scale) > maxWidth) {
      const take = Math.max(1, Math.floor(maxWidth / charW));
      lines.push(w.slice(0, take));
      w = w.slice(take);
    }
    const trial = cur === '' ? w : cur + ' ' + w;
    if (textWidth(trial, scale) <= maxWidth) {
      cur = trial;
    } else {
      if (cur !== '') lines.push(cur);
      cur = w;
    }
  }
  if (cur !== '' || lines.length === 0) lines.push(cur);
  return lines;
}
